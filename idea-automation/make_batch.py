r"""Generate a script (.scr) that applies standards.lsp to every DWG in a folder.

Usage:
    python make_batch.py "C:\Projects\Job123" --lisp "C:\idea-automation\standards.lsp"

Then in IDEA Architecture 24 / 4MCAD:
    Type SCRIPT  ->  select the generated .scr file.

Safety:
    Use --backup "C:\Backups\Job123" to copy the originals first.
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path


def lisp_path(path: Path) -> str:
    """Path usable inside an AutoLISP (load "...") expression."""
    return path.resolve().as_posix().replace('"', "")


def scr_path(path: Path) -> str:
    """Path usable inside a quoted script command."""
    return str(path.resolve()).replace('"', "")


def build_script(files: list[Path], lisp: Path, out: Path) -> None:
    lines = [
        "; Auto-generated by make_batch.py - apply office standards",
        "; Run inside IDEA Architecture 24 / 4MCAD with the SCRIPT command.",
        ".FILEDIA 0",
        ".CMDDIA 0",
    ]
    for dwg in files:
        lines.extend(
            [
                f'.OPEN "{scr_path(dwg)}"',
                f'(load "{lisp_path(lisp)}")',
                "STDSETUP",
                ".QSAVE",
                ".CLOSE",
            ]
        )
    lines.extend([".FILEDIA 1", ".CMDDIA 1", ""])
    out.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Create a batch script that applies standards.lsp to DWG files."
    )
    parser.add_argument("folder", type=Path, help="Folder containing the DWG files")
    parser.add_argument(
        "--lisp",
        type=Path,
        default=Path(__file__).with_name("standards.lsp"),
        help="Path to standards.lsp",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="Output .scr file (default: <folder>/batch_standards.scr)",
    )
    parser.add_argument(
        "--recursive", action="store_true", help="Include subfolders"
    )
    parser.add_argument(
        "--backup",
        type=Path,
        default=None,
        help="Copy original DWGs here before processing",
    )
    args = parser.parse_args()

    folder = args.folder.resolve()
    lisp = args.lisp.resolve()
    if not folder.is_dir():
        raise SystemExit(f"Not a folder: {folder}")
    if not lisp.is_file():
        raise SystemExit(f"LISP file not found: {lisp}")

    candidates = folder.rglob("*") if args.recursive else folder.glob("*")
    files = sorted(
        p for p in candidates if p.is_file() and p.suffix.lower() == ".dwg"
    )

    if not files:
        raise SystemExit(f"No DWG files found in {folder}")

    if args.backup:
        backup_root = args.backup.resolve()
        for dwg in files:
            target = backup_root / dwg.relative_to(folder)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(dwg, target)
        print(f"Backed up {len(files)} file(s) to {backup_root}")

    out = (args.out or folder / "batch_standards.scr").resolve()
    build_script(files, lisp, out)

    print(f"Found {len(files)} DWG file(s).")
    print(f"Wrote: {out}")
    print("In IDEA, type SCRIPT and select that file.")


if __name__ == "__main__":
    main()
